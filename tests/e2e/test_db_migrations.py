"""The initial revision on a real Postgres with PostGIS (rule P8): upgrade, check, downgrade.

Each test gets a database of its own, created on the scratch server of TEST_DATABASE_URL and dropped afterwards:
the extension and the enum types are database-wide, so a schema would not isolate them. Only a database this
fixture generated the name of is ever dropped. A crash can leave a `poc_migrations_*` database behind; drop it by hand.
"""

import asyncio
import importlib
import uuid
from collections.abc import AsyncIterator, Callable
from dataclasses import dataclass
from pathlib import Path
from typing import Concatenate

import pytest
from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import text
from sqlalchemy.engine import make_url
from sqlalchemy.ext.asyncio import AsyncEngine, create_async_engine

from app.config import Settings, get_settings
from app.core.db import Base, create_engine

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
DATABASE_PREFIX = "poc_migrations_"

# Objects PostGIS and Alembic put in the database themselves.
FOREIGN_TABLES = {"alembic_version", "spatial_ref_sys"}


@dataclass
class EmptyDatabase:
    engine: AsyncEngine
    name: str


@pytest.fixture
async def empty_database(
    database_url: str, monkeypatch: pytest.MonkeyPatch
) -> AsyncIterator[EmptyDatabase]:
    """A database created for one test, with DATABASE_URL pointing at it, dropped afterwards."""
    base = make_url(database_url)
    # Generated here, never taken from input: the only name this fixture ever drops.
    name = f"{DATABASE_PREFIX}{uuid.uuid4().hex[:8]}"
    admin = create_async_engine(base, isolation_level="AUTOCOMMIT")
    # The try opens before the database exists, so a failure at any later step still drops it
    # (IF EXISTS: the drop also runs when the create itself failed).
    try:
        async with admin.connect() as connection:
            await connection.execute(text(f'CREATE DATABASE "{name}"'))
        url = base.set(database=name).render_as_string(hide_password=False)
        monkeypatch.setenv("DATABASE_URL", url)
        get_settings.cache_clear()
        engine = create_engine(Settings(database_url=url))
        assert engine is not None
        try:
            yield EmptyDatabase(engine=engine, name=name)
        finally:
            await engine.dispose()
    finally:
        async with admin.connect() as connection:
            await connection.execute(
                text(f'DROP DATABASE IF EXISTS "{name}" WITH (FORCE)')
            )
        await admin.dispose()


async def run[**P](
    function: Callable[Concatenate[Config, P], None], *args: P.args, **kwargs: P.kwargs
) -> None:
    """Run an alembic command on the real env. env.py calls asyncio.run, which cannot nest in this loop."""
    config = Config(str(REPO_ROOT / "alembic.ini"))
    await asyncio.to_thread(function, config, *args, **kwargs)


@pytest.fixture
async def migrated(empty_database: EmptyDatabase) -> EmptyDatabase:
    await run(command.upgrade, "head")
    return empty_database


async def column(engine: AsyncEngine, sql: str) -> list[str]:
    async with engine.connect() as connection:
        return list((await connection.execute(text(sql))).scalars().all())


async def schema_objects(engine: AsyncEngine) -> dict[str, set[str]]:
    """What the database holds, by kind, in the `public` schema."""
    return {
        "tables": set(
            await column(
                engine,
                "select table_name from information_schema.tables "
                "where table_schema = 'public' and table_type = 'BASE TABLE'",
            )
        ),
        "enums": set(
            await column(
                engine,
                "select distinct t.typname from pg_type t join pg_enum e on e.enumtypid = t.oid "
                "where t.typnamespace = 'public'::regnamespace",
            )
        ),
        "indexes": set(
            await column(
                engine,
                "select indexname from pg_indexes where schemaname = 'public' "
                "and tablename not in ('alembic_version', 'spatial_ref_sys')",
            )
        ),
        "foreign_keys": set(
            await column(
                engine,
                "select conname from pg_constraint "
                "where contype = 'f' and connamespace = 'public'::regnamespace",
            )
        ),
    }


def expected_objects() -> dict[str, set[str]]:
    """What the models say the database should hold."""
    importlib.import_module("app.models")
    tables = Base.metadata.tables.values()
    return {
        "tables": {t.name for t in tables} | FOREIGN_TABLES,
        "enums": {"AccountRoleType", "FileType"},
        "indexes": {f"{t.name}_pkey" for t in tables}
        | {index.name for t in tables for index in t.indexes if index.name},
        "foreign_keys": {
            str(fk.name) for t in tables for fk in t.foreign_key_constraints
        },
    }


async def test_upgrade_records_the_revision_and_installs_postgis(
    migrated: EmptyDatabase,
) -> None:
    versions = await column(migrated.engine, "select version_num from alembic_version")
    extensions = await column(migrated.engine, "select extname from pg_extension")

    assert versions == ["0001_init"]
    assert "postgis" in extensions


async def test_upgrade_builds_exactly_the_objects_the_models_declare(
    migrated: EmptyDatabase,
) -> None:
    assert await schema_objects(migrated.engine) == expected_objects()


async def test_check_reports_no_difference_between_the_revision_and_the_models(
    migrated: EmptyDatabase,
) -> None:
    await run(command.check)


async def test_check_fails_when_the_database_lacks_an_index_the_models_declare(
    migrated: EmptyDatabase,
) -> None:
    async with migrated.engine.begin() as connection:
        await connection.execute(text('DROP INDEX "File_createdAt_mimeType_idx"'))

    with pytest.raises(AutogenerateDiffsDetected) as raised:
        await run(command.check)

    assert {(diff[0], diff[1].name) for diff in raised.value.diffs} == {
        ("add_index", "File_createdAt_mimeType_idx")
    }


async def test_downgrade_removes_every_application_object_and_keeps_postgis(
    migrated: EmptyDatabase,
) -> None:
    await run(command.downgrade, "base")

    remaining = await schema_objects(migrated.engine)
    versions = await column(migrated.engine, "select version_num from alembic_version")
    extensions = await column(migrated.engine, "select extname from pg_extension")
    assert remaining == {
        "tables": FOREIGN_TABLES,
        "enums": set(),
        "indexes": set(),
        "foreign_keys": set(),
    }
    assert versions == []
    assert "postgis" in extensions


async def test_the_schema_can_be_built_again_after_a_downgrade(
    migrated: EmptyDatabase,
) -> None:
    await run(command.downgrade, "base")

    await run(command.upgrade, "head")

    assert await schema_objects(migrated.engine) == expected_objects()
    await run(command.check)
